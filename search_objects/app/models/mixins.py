import uuid

from sqlalchemy import CHAR, DateTime, text
from sqlalchemy.orm import Mapped, mapped_column


def new_uuid() -> str:
    """Return a new random UUID as a 36 character string."""
    return str(uuid.uuid4())


class TimestampMixin:
    """Database-managed timestamps; the MySQL container runs in UTC."""

    created_at: Mapped[DateTime] = mapped_column(
        DateTime, nullable=False, server_default=text("CURRENT_TIMESTAMP")
    )
    updated_at: Mapped[DateTime] = mapped_column(
        DateTime,
        nullable=False,
        server_default=text("CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP"),
    )


class UuidMixin:
    """Public identifier generated by the app; unique index for lookups."""

    uuid: Mapped[str] = mapped_column(
        CHAR(36), nullable=False, unique=True, default=new_uuid
    )
